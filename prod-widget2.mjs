import { chromium } from 'playwright-core';
const base='https://kairos-app.live';
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const ctx=await browser.newContext({viewport:{width:1440,height:1100}, colorScheme:'dark', timezoneId:'America/New_York'});
const page=await ctx.newPage();
await page.goto(base+'/login',{waitUntil:'networkidle'});
await page.getByPlaceholder('you@example.com').fill('demo@kairos.app');
await page.getByPlaceholder('Your password').fill('demo1234');
await page.getByRole('button',{name:'Log in',exact:true}).click();
await page.waitForTimeout(3000);
await page.goto(base+'/dashboard',{waitUntil:'networkidle'}); await page.waitForTimeout(1800);
const card = page.locator('section.card').filter({hasText:'Time tracked'}).first();
await card.getByRole('button',{name:'Monthly',exact:true}).click();
await page.waitForTimeout(1000);
console.log((await card.innerText()).split('\n').slice(-10).join(' | '));
await card.screenshot({path:'/tmp/prod-widget-month.png'});
await browser.close();
